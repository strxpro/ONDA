/**
 * Generates supabase/seed.sql from src/content/seed.ts.
 *   npm run db:seed-sql
 * Optional: ADMIN_EMAIL=… ADMIN_TELEGRAM_ID=… npm run db:seed-sql  → also seeds the first admin.
 */
import { writeFileSync } from "node:fs";
import { seed } from "../src/content/seed.ts";

const lit = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v)) return `array[${v.map(lit).join(",")}]::text[]`;
  if (typeof v === "object") return `${lit(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const insert = (table: string, rows: Record<string, unknown>[], conflict: string) => {
  if (!rows.length) return `-- ${table}: no rows\n`;
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols.join(", ")}) values\n${values}\non conflict (${conflict}) do nothing;\n`;
};

const { settings } = seed;
const out = [
  "-- GENERATED by scripts/gen-seed-sql.ts from src/content/seed.ts — do not edit by hand.\n",
  insert("site_settings", [{ id: 1, ...settings }], "id"),
  insert("flavors", seed.flavors, "id"),
  insert("price_items", seed.prices, "id"),
  insert("opening_hours", seed.hours, "weekday"),
  insert("special_days", seed.specialDays, "date"),
  insert("announcements", seed.announcements, "id"),
  insert("sections", seed.sections, "key"),
  insert("gallery", seed.gallery, "id"),
  insert("reviews", seed.reviews, "id"),
];

const email = process.env.ADMIN_EMAIL;
const tg = process.env.ADMIN_TELEGRAM_ID;
if (email || tg) {
  out.push(
    `insert into public.admin_users (email, telegram_user_id, display_name, role) values (${lit(email ?? null)}, ${tg ? Number(tg) : "null"}, 'Mauro', 'owner') on conflict do nothing;\n`,
  );
}

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log("supabase/seed.sql written");
